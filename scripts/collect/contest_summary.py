#!/usr/bin/env python3
"""Validate the contest collections and deterministically render their note.

Run after the collectors: python3 -I scripts/collect/contest_summary.py
Offline verification:    python3 -I scripts/collect/contest_summary.py --check
All numbers in docs/collect/contests_1.md originate here or in the collectors.
"""
import argparse
import collections
import hashlib
import json
from pathlib import Path
import re
import sys
sys.path.insert(0, str(Path(__file__).resolve().parent))
from contest_common import ROOT, iso, read_jsonl

PLATFORMS = ['code4rena', 'sherlock']
NAMES = dict(code4rena='Code4rena', sherlock='Sherlock')
REPORT_FIELDS = set('firm_id collector source_kind public_url listing_url sha256 bytes file_format local_path filename title_hint project_hint date_hint date_precision date_basis doc_kind retrieved_utc notes'.split())
CONTEST_FIELDS = set('contest_id platform name sponsor/project sponsor project start_utc end_utc format report_url findings_high findings_medium sha256'.split())
STATUS_FIELDS = set('firm_id listing_urls listed_count collected failed skipped_non_report failures collected_utc collector_script'.split())


def year(row):
    return row['end_utc'][:4] if row['end_utc'] else 'Unknown'


def validate(platform, contests, reports, status, evidence):
    assert len({c['contest_id'] for c in contests}) == len(contests), platform + ' duplicate IDs'
    assert set(status) == STATUS_FIELDS
    assert status['collected'] == len(reports) and status['failed'] == len(status['failures'])
    listed = [c for c in contests if c.get('listing_member', True)]
    assert len(listed) == status['listed_count'] == evidence['listing_total']
    assert dict(sorted(collections.Counter(year(c) for c in listed).items())) == evidence['listing_end_years']
    report_keys = {(r['public_url'], r['sha256']) for r in reports}
    assert len(report_keys) == len(reports)
    for c in contests:
        assert CONTEST_FIELDS <= set(c)
        assert c['platform'] == platform
        assert c['format'] in {'public_contest', 'private', 'mitigation', 'bounty_boost', 'other'}
        if c['start_utc']:
            assert iso(c['start_utc']) == c['start_utc']
        if c['end_utc']:
            assert iso(c['end_utc']) == c['end_utc']
        for severity in ('high', 'medium'):
            value = c['findings_' + severity]
            assert value is None or isinstance(value, int) and value >= 0
        if c['sha256']:
            assert (c['report_url'], c['sha256']) in report_keys
        if c['report_state'] == 'collected':
            assert c['sha256'] and c['report_url']
    for r in reports:
        assert set(r) == REPORT_FIELDS, (platform, set(r) ^ REPORT_FIELDS)
        assert r['firm_id'] == platform and r['public_url'].startswith('https://')
        if 'github.com/' in r['public_url']:
            assert re.search(r'/blob/[0-9a-f]{40}/', r['public_url'])
        expected = f'local-cache/originals/{r["sha256"][:2]}/{r["sha256"]}.{r["file_format"]}'
        assert r['local_path'] == expected
        body = (ROOT / expected).read_bytes()
        assert len(body) == r['bytes'] and hashlib.sha256(body).hexdigest() == r['sha256']
        if r['file_format'] == 'pdf':
            assert body.startswith(b'%PDF-')
    if platform == 'code4rena':
        expected = evidence['report_listing_count']
        assert sum(bool(c.get('report_listing_uid')) for c in contests) == expected
    elif platform == 'sherlock':
        archive_prefix = f'https://github.com/{evidence["report_archive_repo"]}/blob/{evidence["report_archive_commit"]}/audits/'
        assert sum(r['public_url'].startswith(archive_prefix) for r in reports) == evidence['archive_final_pdf_paths']
    return dict(contests=len(contests), listed=len(listed), reports=len(reports),
                report_urls=len({r['public_url'] for r in reports}),
                contests_with_reports=sum(c['report_state'] == 'collected' for c in contests),
                high=sum(c['findings_high'] or 0 for c in contests), medium=sum(c['findings_medium'] or 0 for c in contests),
                missing_counts=sum(c['findings_high'] is None or c['findings_medium'] is None for c in contests),
                failed=status['failed'], formats=dict(collections.Counter(r['file_format'] for r in reports)))


def render(data, metrics):
    lines = ['# Phase 2c-1: Code4rena and Sherlock', '',
             'Access cutoff: **2026-10-20 UTC**. Generated by `scripts/collect/contest_summary.py` from the collectors’ saved official-source snapshots and manifests. ' 
             'The tables use **UTC contest end year**. The full inventory retains private/invitational, mitigation and bounty formats; ' 
             'only finalized public competitions belong in the primary contest cohort. Source statuses are preserved rather than inferred from elapsed time. ' 
             'Unknown dates and unavailable finding totals remain null.', '',
             '| Platform | Official listing IDs | Inventory IDs | Contests with collected final report | Collected files | Failures |',
             '|---|---:|---:|---:|---:|---:|']
    for p in PLATFORMS:
        m = metrics[p]
        lines.append(f'| {NAMES[p]} | {m["listed"]} | {m["contests"]} | {m["contests_with_reports"]} | {m["reports"]} | {m["failed"]} |')
    lines.extend(['', 'Files and engagements are different units: Code4rena HTML/Markdown renditions and Sherlock archive PDFs must not be added to the contest denominator. ' 
                  'The release contains metadata and original links; report bytes and raw HTTP responses remain in gitignored `local-cache/`.', ''])
    for p in PLATFORMS:
        contests, reports, status, evidence = data[p]
        m = metrics[p]
        lines.extend(['## ' + NAMES[p], '',
                      f'Official comparison: [{evidence["listing_url"]}]({evidence["listing_url"]}), **{status["listed_count"]} unique listing IDs**. ' 
                      'Each year’s listing count is independently recomputed from the captured source records and checked against the output’s listing-member subset.', '',
                      '| End year | Official listing | Inventory | Public competition | Private/invitational | Mitigation | Bounty/Boost | Other | Finalized public cohort |',
                      '|---|---:|---:|---:|---:|---:|---:|---:|---:|'])
        for y in sorted(set(year(c) for c in contests)):
            cohort = [c for c in contests if year(c) == y]
            kinds = collections.Counter(c['format'] for c in cohort)
            eligible = sum(c['format'] == 'public_contest' and c['finalized'] for c in cohort)
            values = [evidence['listing_end_years'].get(y, 0), len(cohort)] + [kinds[k] for k in ['public_contest','private','mitigation','bounty_boost','other']] + [eligible]
            lines.append('| ' + y + ' | ' + ' | '.join(map(str, values)) + ' |')
        lines.extend(['', '2026 is year to date at the access cutoff. ' 
                      f'Known official canonical counts: **{m["high"]} high / {m["medium"]} medium**; '
                      f'**{m["missing_counts"]} contests have an unknown or unextracted high/medium total**. These are coverage totals, not an assertion that missing findings equal zero.', ''])
        if p == 'code4rena':
            lines.append(f'The fully paginated audit API advertises {evidence["listing_total"]} IDs; the separate [report index](https://code4rena.com/reports) lists {evidence["report_listing_count"]} reports. ' 
                         f'The union retains {len(evidence["report_only_contests"])} report-only IDs absent from the audit API: ' + ', '.join(f'{r["contest_id"]} (`{r["slug"]}`)' for r in evidence['report_only_contests']) + '. ' 
                         'These explain the inventory-versus-listing difference; no rows are discarded to force equality. The listing-member subset reconciles exactly by year.')
            lines.extend(['', '`auditType` and raw `codeAccess` are retained. `certified` and `top_secret` audits are grouped under private/invitational; standalone mitigation reviews have their own format, and bundled audit-plus-mitigation engagements remain one contest. ' 
                          'Accepted H/M totals come from the final report Summary or unique canonical report headings, never GitHub submission counts. ' 
                          'A published final report establishes finalization even when the older audit API retains a null or preparation status. ' 
                          'Formal-verification-only competitions are classified as `other`. Native findings-repository Markdown is preferred and pinned to its repository commit; website HTML originals are also retained. ' 
                          'Where a repository has no public native Markdown, the HTML is accompanied by an explicitly labelled derived Markdown reading rendition. The two historical PDF-only reports retain their original source links; a link stub is never accepted as a report.', ''])
            native_md = sum(r['file_format'] == 'md' and 'Native official findings-repository' in r['notes'] for r in reports)
            derived_md = sum(r['file_format'] == 'md' and r['notes'].startswith('Derived Markdown') for r in reports)
            lines.extend([f'Collected Markdown: {native_md} publisher originals and {derived_md} derived reading renditions. ' 
                          f'{len(evidence.get("mitigation_report_links", []))} mitigation reviews link to their parent’s collected final report by an exact scope-repository URL in the mitigation appendix. ' 
                          'These links do not create additional report files. Only explicitly summarized new mitigation findings are counted; original unmitigated issues are not counted again. Positive totals combined across rounds remain unassigned to individual rounds.', '',
                          'Dead-link recovery: ElasticDAO’s PDF uses the publisher-linked IPFS content ID through the Filebase public gateway. Slingshot’s PDF was recovered from a revision-pinned public Hugging Face mirror and checked against the archived catalog’s exact byte size and SHA-256. ' 
                          'Tapioca’s missing website page was recovered as native Markdown from its official findings repository. All recovery provenance is recorded in the manifests.', ''])
        elif p == 'sherlock':
            if evidence.get('stats_listing_discrepancy'):
                lines.extend([evidence['stats_listing_discrepancy'], ''])
            lines.append(f'The API enumerates {evidence["listing_public"]} public and {evidence["listing_private"]} private records. ' 
                         '`Public Best Efforts` remains a public competition with its raw type and best-efforts flag; bug-bounty types are separated. ' 
                         'Exact final report Markdown is extracted from the official detail response. When that field is absent, the official judging repository is checked for its final PDF/Markdown and canonical exported groups. ' 
                         'Private contest detail bodies are not requested.')
            lines.extend(['', f'The pinned [official report archive](https://github.com/sherlock-protocol/sherlock-reports/tree/{evidence["report_archive_commit"]}/audits) contains {evidence["archive_pdf_paths"]} PDFs under `audits/`: ' 
                          f'{evidence["archive_final_pdf_paths"]} non-preliminary reports are collected; {len(evidence["excluded_preliminary"])} explicitly preliminary report is excluded. ' 
                          'Coverage agreements are excluded. Archive reports without an exact official contest-ID association remain documents; filename issue dates never become contest end dates or additional contest IDs.', ''])
        uncollected = [c for c in contests if c['report_state'] != 'collected']
        states = collections.Counter(c['report_state'] for c in uncollected)
        if states:
            lines.append('Other inventory states: ' + ', '.join(f'`{k}` = {v}' for k, v in sorted(states.items())) + '. These rows are retained in `contests.jsonl`.')
            lines.append('')
        for f in status['failures']:
            lines.extend([f'- Collection gap: [{f["url"]}]({f["url"]}) — {f["error"]}', ''])
    lines.extend(['## Reproduction and checks', '', '```sh',
                  'python3 -I scripts/collect/contest_code4rena.py', 'python3 -I scripts/collect/contest_sherlock.py',
                  'python3 -I scripts/collect/contest_summary.py',
                  '# With the saved local-cache snapshots, rerun each collector with --offline.',
                  'python3 -I scripts/collect/contest_summary.py --check', '```', '',
                  'Collectors use a descriptive User-Agent, robots.txt checks, and a shared host lock limiting network requests to at most one per second. ' 
                  'No authentication, login/paywall bypass, publisher code execution or Git commits are used. GitHub documents use commit-pinned blob links. ' 
                  'Same-day primary-source snapshots from the earlier repository research may be reused after SHA-256 verification; `--refresh` deliberately requests new snapshots. ' 
                  'Checks cover required contract fields, unique IDs, full pagination totals, yearly listing reconciliation, report associations, exact local byte sizes and SHA-256 hashes, PDF signatures, and this note’s deterministic regeneration. ' 
                  'The census establishes coverage of publicly observable official listings and archives; it cannot establish the existence or dates of undisclosed private engagements.', ''])
    return '\n'.join(lines)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    opts = parser.parse_args()
    data, metrics = {}, {}
    for p in PLATFORMS:
        out = ROOT / 'data' / 'collect' / p
        data[p] = (read_jsonl(out / 'contests.jsonl'), read_jsonl(out / 'reports.jsonl'),
                   json.loads((out / 'status.json').read_text()), json.loads((out / 'reconciliation.json').read_text()))
        metrics[p] = validate(p, *data[p])
    note = render(data, metrics)
    path = ROOT / 'docs' / 'collect' / 'contests_1.md'
    if opts.check:
        assert path.read_text() == note, 'Regenerate docs/collect/contests_1.md'
        assert all(m['failed'] == 0 for m in metrics.values()), 'Collection failures remain'
        assert all(c['report_state'] == 'collected' for c in data['code4rena'][0] if c.get('report_listing_uid')), 'Published C4 report remains uncollected'
    else:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(note)
    print(json.dumps(metrics, indent=2, sort_keys=True))


if __name__ == '__main__':
    main()
